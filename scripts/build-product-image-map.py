"""Compile reviewed photo metadata. Never writes product or price records."""
import json
from collections import Counter
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
ALLOWED_HOSTS = {'kss.uz', 'mfs.ezvizlife.com', 'static.tp-link.com'}
# These images failed the visual model check, despite matching supplier labels.
REJECTED = {884: 'Supplier photo shows a cable, not this Linkff switch.',
            885: 'Supplier photo shows a cable, not this Linkff switch.',
            77: 'Existing image depicts a relay, not the named CPU card.'}
KEEP_VERIFIED = {10, 11, 26, 27, 79}


def adequate(size):
    return size and min(size) >= 200 and max(size) >= 400 and size[0] * size[1] >= 80000


def main():
    report = json.loads((ROOT / '.data/image-review/base-review.json').read_text())
    records = {row['id']: row for row in report['products']}
    overrides = json.loads((ROOT / 'assets/official-products/reviewed-sources.json').read_text())['products']
    for row in overrides:
        if row['id'] in records and (row['status'] in ['official-candidate', 'candidate-exact-model'] or records[row['id']]['status'] == 'needs-exact-source'):
            previous_dimensions = records[row['id']].get('previousDimensions')
            records[row['id']] = {**row, 'previousDimensions': previous_dimensions}
    local = json.loads((ROOT / 'assets/official-products/sources.json').read_text())['products']
    local_by_model = {(row['brand'], row['model']): row for row in local}
    compiled = []
    for row in sorted(records.values(), key=lambda item: item['id']):
        original = row['previousImage']
        if original and not original.startswith(('assets/kss/', 'assets/ezviz/', 'assets/neocam/')):
            row['status'] = 'keep-custom-image'
            continue
        if row['id'] in REJECTED:
            row['status'] = 'needs-model-photo-review'
            row['reviewNote'] = REJECTED[row['id']]
            continue
        known_local = local_by_model.get((row['brand'], row['model']))
        if known_local:
            row['status'] = 'replacement-ready-local'
            row['selectedImage'] = known_local['image']
            continue
        if row['id'] in KEEP_VERIFIED:
            row['status'] = 'keep-existing-quality'
            continue
        size = row.get('sourceDimensions')
        source = row.get('sourceImage', '')
        parsed = urlparse(source)
        if row['status'] in ['candidate-exact-model', 'official-candidate', 'source-too-small'] and adequate(size) and parsed.scheme == 'https' and parsed.hostname in ALLOWED_HOSTS:
            old = row.get('previousDimensions')
            if row['status'] != 'official-candidate' and old and size[0] * size[1] < old[0] * old[1] * 1.5:
                row['status'] = 'keep-source-not-better'
                continue
            row['status'] = 'replacement-ready'
            row['selectedImage'] = source
            compiled.append([row['brand'], row['model'], original, '/api/reviewed-product-images/' + str(row['id']) + '/' + row['sha256'][:12]])
        elif row['status'] == 'keep-resolution-adequate':
            row['status'] = 'keep-existing-quality'
    report['products'] = sorted(records.values(), key=lambda item: item['id'])
    report['summary'] = dict(Counter(row['status'] for row in report['products']))
    report['criteria'] = 'Full model and variant match; native image dimensions; visual contact-sheet inspection; source URLs recorded. Custom admin images preserved. No AI upscaling. Uncertain matches excluded.'
    report['delivery'] = 'Reviewed external sources with legacy-image fallback; seven bundled manufacturer PNGs. No prices or database images are overwritten.'
    (ROOT / 'assets/product-image-audit.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    (ROOT / 'assets/reviewed-product-images.js').write_text('// Generated by scripts/build-product-image-map.py.\nwindow.UzCamReviewedPhotos=' + json.dumps(compiled, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(json.dumps(report['summary'], ensure_ascii=False))


if __name__ == '__main__':
    main()
